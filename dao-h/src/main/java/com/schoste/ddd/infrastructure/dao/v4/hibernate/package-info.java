/**
 * A DAO (Data Access Object) which stores data objects in a database via Hibernate 5.6:
 * {@link com.schoste.ddd.infrastructure.dao.v4.hibernate.AbstractHibernateDAO}.
 * Data objects are deleted logically (the deleted flag is a column); time stamps come from the database's clock.
 * Every operation runs in its own session and transaction; a returned stream keeps its session open until the stream is closed.
 *
 * Example of a DAO for the data object {@code CustomerDO} (see the overview of the {@code dao4} artifact), created without
 * a framework:
 * <pre>
 * import java.util.Arrays;
 * import java.util.HashMap;
 * import java.util.Map;
 *
 * import org.hibernate.SessionFactory;
 *
 * import com.schoste.ddd.infrastructure.dao.v4.hibernate.AbstractHibernateDAO;
 * import com.schoste.ddd.infrastructure.dao.v4.hibernate.SessionFactoryBuilder;
 * import com.schoste.ddd.infrastructure.dao.v4.services.DAO;
 *
 * public class CustomerDAO extends AbstractHibernateDAO&lt;Long, CustomerDO&gt;
 * {
 *     private final SessionFactory sessionFactory;
 *     private long lastVirtualId = 0;
 *
 *     public CustomerDAO(SessionFactory sessionFactory) { this.sessionFactory = sessionFactory; }
 *
 *     protected SessionFactory getSessionFactory() { return this.sessionFactory; }
 *
 *     protected CustomerDO doCreateDataObject() { return new CustomerDO(); }
 *
 *     // virtual ids are negative, the database generates positive actual ids
 *     protected synchronized Long doCreateVirtualId() { return --this.lastVirtualId; }
 *     protected boolean doIsVirtualId(Long id) { return id &lt;= 0; }
 * }
 *
 * Map&lt;String, Object&gt; settings = new HashMap&lt;&gt;();
 * settings.put("hibernate.connection.url", "jdbc:postgresql://localhost/example");
 * settings.put("hibernate.connection.driver_class", "org.postgresql.Driver");
 * settings.put("hibernate.connection.username", "example");
 * settings.put("hibernate.connection.password", "secret");
 * settings.put("hibernate.dialect", "org.hibernate.dialect.PostgreSQL95Dialect");
 *
 * SessionFactory sessionFactory = SessionFactoryBuilder.buildSessionFactory(settings, Arrays.asList("META-INF/customers.xml"));
 * DAO&lt;Long, CustomerDO&gt; dao = new CustomerDAO(sessionFactory);
 * </pre>
 *
 * The data objects are mapped by Hibernate's usual means. {@link com.schoste.ddd.infrastructure.dao.v4.models.DataObject} is
 * mapped as mapped superclass with field access; the entity name of a data object class is its simple class name, unless
 * {@code getEntityName()} is overridden. The database schema isn't created by the DAO; create it yourself (or set Hibernate's
 * {@code hibernate.hbm2ddl.auto}). Example of {@code META-INF/customers.xml} for a table
 * {@code customer(id BIGINT GENERATED BY DEFAULT AS IDENTITY, created BIGINT, modified BIGINT, deleted BOOLEAN, name VARCHAR(255))}:
 * <pre>
 * &lt;entity-mappings xmlns="http://java.sun.com/xml/ns/persistence/orm" version="2.0"&gt;
 *     &lt;mapped-superclass class="com.schoste.ddd.infrastructure.dao.v4.models.DataObject" access="FIELD"&gt;
 *         &lt;attributes&gt;
 *             &lt;id name="id"&gt;&lt;generated-value strategy="IDENTITY"/&gt;&lt;/id&gt;
 *             &lt;basic name="createdTimestamp"&gt;&lt;column name="created"/&gt;&lt;/basic&gt;
 *             &lt;basic name="modifiedTimestamp"&gt;&lt;column name="modified"/&gt;&lt;/basic&gt;
 *             &lt;basic name="deleted"&gt;&lt;column name="deleted"/&gt;&lt;/basic&gt;
 *         &lt;/attributes&gt;
 *     &lt;/mapped-superclass&gt;
 *     &lt;entity class="com.example.CustomerDO" name="CustomerDO"&gt;
 *         &lt;table name="customer"/&gt;
 *     &lt;/entity&gt;
 * &lt;/entity-mappings&gt;
 * </pre>
 *
 * @author Philipp Schosteritsch &lt;s.philipp@schoste.com&gt;
 */
