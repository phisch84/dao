package com.schoste.ddd.infrastructure.dal.v3.services.hibernate;

import org.hibernate.SessionFactory;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.context.ApplicationContext;

import com.schoste.ddd.infrastructure.dal.v3.exceptions.DALException;
import com.schoste.ddd.infrastructure.dal.v3.models.HibernateDO;
import com.schoste.ddd.infrastructure.dal.v3.services.HibernateDAO;

/**
 * Example Hibernate data access object used in unit testing of the GenericHibernateDAO implementation
 *
 * @author Philipp Schosteritsch <s.philipp@schoste.com>
 *
 */
public class HibernateDAOImpl extends GenericHibernateDAO<Long, HibernateDO> implements HibernateDAO
{
	@Autowired
	protected ApplicationContext applicationContext;
	protected long lastVirtualId=0;

	@Autowired
	protected SessionFactory sessionFactory;

	/**
	 * {@inheritDoc}
	 *
	 * Returns the session factory injected by Spring.
	 */
	protected SessionFactory getSessionFactory()
	{
		return this.sessionFactory;
	}

	/**
	 * {@inheritDoc}
	 *
	 * The data object is obtained from Spring's application context.
	 */
	@Override
	public HibernateDO createDataObject()
	{
		HibernateDO dataObject = (HibernateDO) this.applicationContext.getBean(HibernateDO.class);
		
		return dataObject;
	}

	/**
	 * {@inheritDoc}
	 *
	 * Negative identifiers are virtual.
	 *
	 * @throws NullPointerException thrown if the id is null
	 */
	@Override
	public boolean isVirtualId(Long id)
	{
		return (id < 0L);
	}

	/**
	 * {@inheritDoc}
	 */
	@Override
	protected HibernateDO doCreateDataObject(Object... args) throws Exception
	{
		try
		{
			HibernateDO dataObj = (HibernateDO) this.applicationContext.getBean(HibernateDO.class);

			return dataObj;
		}
		catch (Exception ex)
		{
			throw new DALException(ex);
		}
	}

	/**
	 * Placeholder implementation that is not used: actual identifiers are generated by Hibernate when
	 * a data object is saved. It returns the current time in milliseconds, which is neither guaranteed to be unique
	 * nor related to any data object in the storage.
	 *
	 * @param args not used
	 * @return the current time in milliseconds
	 * @throws Exception re-throws every exception
	 */
	@Override
	protected Long getActualId(Object... args) throws Exception
	{
		Long actualId = System.currentTimeMillis();

		return actualId;
	}

	/**
	 * {@inheritDoc}
	 *
	 * Virtual identifiers are negative and strictly decreasing, derived from the current time in milliseconds.
	 */
	@Override
	protected Long getNextVirtualId(Object... args) throws Exception
	{
		long virtualId = System.currentTimeMillis()*(-1);

		while (this.lastVirtualId <= virtualId) virtualId--;

		this.lastVirtualId = virtualId;

		return virtualId;
	}
}
